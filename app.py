# -----------------------------
# Input helper
# -----------------------------
def create_inputs(features, defaults):
    values = []

    for i in range(0, len(features), 2):
        col1, col2 = st.columns(2)

        with col1:
            value1 = st.number_input(
                features[i],
                min_value=0.0,
                value=float(defaults[i]),
                format="%.6f",
                key=features[i]
            )
            values.append(value1)

        if i + 1 < len(features):
            with col2:
                value2 = st.number_input(
                    features[i + 1],
                    min_value=0.0,
                    value=float(defaults[i + 1]),
                    format="%.6f",
                    key=features[i + 1]
                )
                values.append(value2)

    return values
# -----------------------------
# Mean Features
# -----------------------------
st.header("📊 Mean Features")

st.caption(
    "Average measurements of the cell nuclei."
)

mean_values = create_inputs(
    mean_features,
    default_values[:10]
)


# -----------------------------
# Error Features
# -----------------------------
st.header("📐 Error Features")

st.caption(
    "Standard error measurements of the diagnostic features."
)

error_values = create_inputs(
    error_features,
    default_values[10:20]
)


# -----------------------------
# Worst Features
# -----------------------------
st.header("🔬 Worst Features")

st.caption(
    "Largest or most significant measurements recorded for the cell nuclei."
)

worst_values = create_inputs(
    worst_features,
    default_values[20:30]
)


# -----------------------------
# Combine all inputs
# -----------------------------
inputs = mean_values + error_values + worst_values


# -----------------------------
# Prediction button
# -----------------------------
st.divider()

if st.button(
    "🔍 Predict",
    use_container_width=True
):

    input_data = np.array(inputs).reshape(1, -1)

    prediction = model.predict(input_data)[0]

    st.header("Prediction Result")

    if prediction == 0:

        st.error(
            "🔴 Prediction: Malignant"
        )

    else:

        st.success(
            "🟢 Prediction: Benign"
        )

    st.info(
        "The prediction is generated by the trained machine learning model "
        "using the 30 diagnostic features entered above."
    )