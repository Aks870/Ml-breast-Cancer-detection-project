# -----------------------------
# Page configuration
# -----------------------------
st.set_page_config(
    page_title="Breast Cancer Detection",
    page_icon="🩺",
    layout="wide"
)


# -----------------------------
# Header
# -----------------------------
st.title("🩺 Breast Cancer Detection")

st.write(
    "Enter the diagnostic measurements below to get a prediction "
    "from the trained machine learning model."
)

st.warning(
    "⚠️ This application is for educational and demonstration purposes only. "
    "It is not a medical diagnosis."
)


# -----------------------------
# Feature names
